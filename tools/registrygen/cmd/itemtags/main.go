// Command itemtags compacts the shared native item-tag catalog into the
// tab-separated table the protocol crate embeds.
package main

import (
	"flag"
	"fmt"
	"io"
	"os"
	"regexp"
	"sort"
	"strings"

	shared "github.com/cinnabar-mc/protocolgen/generated/data"
	shareditem "github.com/cinnabar-mc/protocolgen/generated/data/item"
)

var identifier = regexp.MustCompile(`^[a-z0-9_.-]+:[a-z0-9_./-]+$`)

func main() {
	flag.Parse()
	if err := run(os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// run writes memberships from the authenticated shared runtime catalog.
func run(output io.Writer) error {
	table, err := compact(shareditem.RuntimeItems(), shareditem.RuntimeTags)
	if err != nil {
		return err
	}
	_, err = io.WriteString(output, table)
	return err
}

// compact reverses item memberships without mutating borrowed catalog slices.
func compact(items []shareditem.Runtime, tagsForItem func(string) []string) (string, error) {
	if len(items) == 0 {
		return "", fmt.Errorf("shared item registry is empty")
	}
	tags := make(map[string][]string)
	seen := make(map[string]bool, len(items))
	for _, item := range items {
		if !identifier.MatchString(item.Name) || seen[item.Name] {
			return "", fmt.Errorf("invalid or duplicate item %q", item.Name)
		}
		seen[item.Name] = true
		for _, tag := range tagsForItem(item.Name) {
			tags[tag] = append(tags[tag], item.Name)
		}
	}
	names := make([]string, 0, len(tags))
	for tag := range tags {
		names = append(names, tag)
	}
	sort.Strings(names)
	var out strings.Builder
	fmt.Fprintf(&out, "# Generated by tools/registrygen/cmd/itemtags from protocolgen/generated/data source_lock_sha256=%s native_ref=%s; do not edit.\n",
		shared.SourceLockSHA256, shared.NativeRef)
	for _, tag := range names {
		items := tags[tag]
		sort.Strings(items)
		if !identifier.MatchString(tag) {
			return "", fmt.Errorf("invalid tag %q", tag)
		}
		for index, item := range items {
			if index > 0 && items[index-1] == item {
				return "", fmt.Errorf("tag %s has a duplicate item %q", tag, item)
			}
		}
		fmt.Fprintf(&out, "%s\t%s\n", tag, strings.Join(items, " "))
	}
	return out.String(), nil
}
