"""Render the private Dragonfly process protocol for its actual Rust/Go consumers."""

import json
import subprocess


def declarations(root):
    """Keep process message identities, records and bounded flow in one source."""
    source = json.loads((root / "crates/bridge/data/host-world.json").read_text(encoding="utf-8"))
    shared = json.loads((root / "crates/bridge/data/contract.json").read_text(encoding="utf-8"))
    control = next(row["value"] for row in shared["constants"]
                   if row["rust_name"] == "CONTROL_MAX_FRAME_LEN")
    constants = {"VERSION": source["version"], "MAX_CONTROL_BYTES": control,
                 **source["constants"]}
    for name, shared_name in source.get("shared_constants", {}).items():
        constants[name] = next(row["value"] for row in shared["constants"]
                               if row["rust_name"] == shared_name)
    rust = ["// Generated by tools/bridgegen/host_world.py; edit data/host-world.json.",
            "use serde::{Deserialize, Serialize};", ""]
    go = ["// Code generated by tools/bridgegen/host_world.py; DO NOT EDIT.",
          "// Package hostcontract defines the private Dragonfly process bridge.",
          "package hostcontract", "", 'import "encoding/json"', "", "const ("]
    for name, value in constants.items():
        rust += [f"/// Private process protocol {name.lower().replace('_', ' ')}.",
                 f"pub const {name}: u32 = {value};"]
        go += [f"    {name} = {value}"]
    rust += ["/// Private stdin bootstrap command prefix.",
             f'pub const COMMAND: &str = {json.dumps(source["command"])};', ""]
    go += [f'    COMMAND = {json.dumps(source["command"])}', ")", ""]
    rust += ["/// One direction permits one Packet/Flush until Flushed; controls remain readable.",
             "#[derive(Clone, Copy, Debug, Eq, PartialEq)]", "#[repr(u8)]", "pub enum Kind {"]
    go += ["// Kind identifies one phase-checked private process frame.", "type Kind byte", "const ("]
    for name, number, _ in source["kinds"]:
        rust += [f"    /// {name} process frame.", f"    {name} = {number},"]
        go += [f"    Kind{name} Kind = {number}"]
    rust += ["}", "impl Kind {", "    /// Rejects unknown process frame kinds.",
             "    pub fn parse(value: u8) -> Option<Self> {", "        Some(match value {"]
    for name, number, _ in source["kinds"]:
        rust += [f"            {number} => Self::{name},"]
    rust += ["            _ => return None,", "        })", "    }",
             "    /// Maximum body bytes, before JSON/packet decoding.",
             "    pub fn maximum(self) -> usize {", "        match self {"]
    go += [")", "", "// Maximum returns the body bound, or zero for an unknown kind.",
           "func (k Kind) Maximum() uint32 {", "    switch k {"]
    for name, _, bound in source["kinds"]:
        maximum = {"control": "MAX_CONTROL_BYTES", "packet": "MAX_PACKET_BYTES",
                   "pack": "MAX_PACK_READ_BYTES"}[bound]
        rust += [f"            Self::{name} => {maximum} as usize,"]
        go += [f"    case Kind{name}: return {maximum}"]
    rust += ["        }", "    }", "}", ""]
    go += ["    default: return 0", "    }", "}", ""]
    primitive = {"string": ("String", "string"), "u32": ("u32", "uint32"),
                 "u64": ("u64", "uint64"), "bool": ("bool", "bool"),
                 "raw": ("Box<serde_json::value::RawValue>", "json.RawMessage")}
    for name, fields in source["records"].items():
        rust += [f"/// Bounded {name} process metadata; deliberately omits Debug.",
                 "#[derive(Serialize, Deserialize)]", "#[serde(deny_unknown_fields)]",
                 f"pub struct {name} {{"]
        go += [f"// {name} carries bounded private process metadata.", f"type {name} struct {{"]
        for field, kind in fields:
            if kind.startswith("list:"):
                rust_type, go_type = f"Vec<{kind[5:]}>", f"[]{kind[5:]}"
            else:
                rust_type, go_type = primitive.get(kind, (kind, kind))
            go_field = "".join(part[:1].upper() + part[1:] for part in field.split("_"))
            rust += [f"    /// Original {field.replace('_', ' ')}.", f"    pub {field}: {rust_type},"]
            go += [f'    {go_field} {go_type} `json:"{field}"`']
        rust += ["}", ""]
        go += ["}", ""]
    def formatted(command, lines):
        """Return exactly the checked-in formatter output for generated declarations."""
        return subprocess.run(command, input="\n".join(lines) + "\n", encoding="utf-8",
                              capture_output=True, check=True).stdout
    return {
        root / "crates/bridge/src/host_world/contract.rs": formatted(
            ["rustfmt", "--edition", "2024", "--emit", "stdout"], rust),
        root / "tools/localserver/internal/hostcontract/contract.go": formatted(["gofmt"], go),
    }
