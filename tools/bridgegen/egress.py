"""Generate the gateway's Go/Rust address policy and shared boundary corpus."""

import ipaddress
import json
import subprocess


CLASSES = {
    "ipv4_unspecified", "ipv4_broadcast", "ipv4_loopback", "ipv4_multicast",
    "ipv4_link_local", "ipv4_private_a", "ipv4_private_b", "ipv4_private_c",
    "ipv6_unspecified", "ipv6_loopback", "ipv6_multicast", "ipv6_link_local",
    "ipv6_private",
}


def networks(rows, classes=False):
    """Validate canonical bounded prefixes before emitting infallible numeric bindings."""
    if not isinstance(rows, list) or not 0 < len(rows) <= 64:
        raise ValueError("gateway prefixes must be a nonempty bounded list")
    result, seen, kinds = [], set(), set()
    for row in rows:
        keys = {"cidr", "reason", "kind"} if classes else {"cidr", "reason"}
        if not isinstance(row, dict) or set(row) != keys:
            raise ValueError("unsupported gateway prefix fields")
        if not isinstance(row["reason"], str) or not row["reason"].strip():
            raise ValueError("gateway prefixes need a reason")
        network = ipaddress.ip_network(row["cidr"], strict=True)
        if str(network) != row["cidr"] or network in seen:
            raise ValueError("gateway prefixes must be canonical and unique")
        if classes:
            kind = row["kind"]
            if kind not in CLASSES or kind in kinds or not kind.startswith(f"ipv{network.version}_"):
                raise ValueError("invalid gateway address class")
            kinds.add(kind)
        seen.add(network)
        result.append(network)
    if classes and kinds != CLASSES:
        raise ValueError("gateway address classification is incomplete")
    return result


def admitted(address, denied):
    """Classify zone-free corpus addresses after only IPv4-mapped normalization."""
    if isinstance(address, ipaddress.IPv6Address) and address.ipv4_mapped is not None:
        address = address.ipv4_mapped
    return not any(address.version == prefix.version and address in prefix for prefix in denied)


def address_text(address):
    """Render mapped IPv6 consistently across supported Python versions."""
    if isinstance(address, ipaddress.IPv6Address) and address.ipv4_mapped is not None:
        return f"::ffff:{address.ipv4_mapped}"
    return str(address)


def corpus(denied, examples):
    """Probe both sides of every boundary and the mapped form of every IPv4 probe."""
    addresses = set()
    for prefix in denied:
        first, last = int(prefix.network_address), int(prefix.broadcast_address)
        maximum = (1 << prefix.max_prefixlen) - 1
        constructor = ipaddress.IPv4Address if prefix.version == 4 else ipaddress.IPv6Address
        for value in (first - 1, first, first + 1, last - 1, last, last + 1):
            if 0 <= value <= maximum:
                addresses.add(constructor(value))
    if not isinstance(examples, list) or not 0 < len(examples) <= 64:
        raise ValueError("gateway examples must be a nonempty bounded list")
    for text in examples:
        if not isinstance(text, str) or "%" in text:
            raise ValueError("gateway corpus uses zone-free IP addresses")
        addresses.add(ipaddress.ip_address(text))
    for address in tuple(addresses):
        if address.version == 4:
            addresses.add(ipaddress.IPv6Address((0xFFFF << 32) | int(address)))
    if len(addresses) > 1024:
        raise ValueError("gateway boundary corpus exceeds its bound")
    return {
        "schema": 1,
        "cases": [{"address": address_text(address), "public": admitted(address, denied)}
                  for address in sorted(addresses, key=lambda ip: (ip.version, int(ip)))],
    }


def declarations(manifest, root):
    """Render one actual Go policy, its Rust equivalent and a common conformance corpus."""
    if not isinstance(manifest, dict) or set(manifest) != {
        "schema", "normalization", "classification", "classes", "reserved", "examples"
    }:
        raise ValueError("unsupported gateway policy fields")
    if (type(manifest["schema"]) is not int or manifest["schema"] != 1
            or manifest["normalization"] != "ipv4-mapped"
            or manifest["classification"] != "go-netip-global-unicast-not-private"):
        raise ValueError("unsupported gateway address policy")
    classes = networks(manifest["classes"], classes=True)
    reserved = networks(manifest["reserved"])
    denied = classes + reserved
    if len(set(denied)) != len(denied):
        raise ValueError("duplicate gateway class/reserved prefix")
    rust = [
        "// Generated by tools/bridgegen/generate.py; edit data/gateway-egress.json.",
        "//! Zone-free gateway address admission shared with the Go product edge.",
        "", "use std::net::IpAddr;",
    ]
    for version, bits in ((4, 32), (6, 128)):
        ranges = [prefix for prefix in denied if prefix.version == version]
        rust += ["", f"const DENIED_V{version}: [(u{bits}, u{bits}); {len(ranges)}] = ["]
        for prefix in ranges:
            network = f"0x{int(prefix.network_address):0{bits // 4}x}"
            mask = f"0x{int(prefix.netmask):0{bits // 4}x}"
            if version == 4:
                rust.append(f"    ({network}, {mask}),")
            else:
                rust += ["    (", f"        {network},", f"        {mask},", "    ),"]
        rust += ["];"]
    rust += [
        "", "/// Admits only the gateway's public unicast destinations after IPv4-mapped normalization.",
        "/// This classifies an actual resolved IP, not a hostname, URL, account or socket permit.",
        "/// Zone/scope parsing belongs to the connecting edge; `IpAddr` carries no zone.",
        "#[must_use]", "pub fn public_gateway_upstream(address: IpAddr) -> bool {",
        "    let address = match address {",
        "        IpAddr::V6(address) => address",
        "            .to_ipv4_mapped()",
        "            .map_or(IpAddr::V6(address), IpAddr::V4),",
        "        address => address,", "    };", "    match address {",
        "        IpAddr::V4(address) => {", "            let value = u32::from(address);",
        "            !DENIED_V4", "                .iter()",
        "                .any(|(network, mask)| value & *mask == *network)", "        }",
        "        IpAddr::V6(address) => {", "            let value = u128::from(address);",
        "            !DENIED_V6", "                .iter()",
        "                .any(|(network, mask)| value & *mask == *network)", "        }",
        "    }", "}", "", "#[cfg(test)]", "mod tests;", "",
    ]
    go = [
        "// Code generated by tools/bridgegen/generate.py; DO NOT EDIT.",
        "package bridgecontract", "", 'import "net/netip"', "",
        "var gatewayReservedPrefixes = [...]netip.Prefix{",
    ]
    for prefix in reserved:
        width = 4 if prefix.version == 4 else 16
        octets = ", ".join(str(value) for value in prefix.network_address.packed)
        go.append(f"netip.PrefixFrom(netip.AddrFrom{width}([{width}]byte{{{octets}}}), {prefix.prefixlen}),")
    go += [
        "}", "", "// GatewayReservedPrefixes returns a copy of the gateway's extra denied prefixes.",
        f"func GatewayReservedPrefixes() [{len(reserved)}]netip.Prefix {{ return gatewayReservedPrefixes }}",
        "", "// PublicGatewayUpstream preserves Go's original address/zone semantics and extra exclusions.",
        "func PublicGatewayUpstream(addr netip.Addr) bool {", "addr = addr.Unmap()",
        "if !addr.IsValid() || !addr.IsGlobalUnicast() || addr.IsPrivate() { return false }",
        "for _, prefix := range gatewayReservedPrefixes { if prefix.Contains(addr) { return false } }",
        "return true", "}", "",
    ]
    formatted_go = subprocess.run(["gofmt"], input="\n".join(go), encoding="utf-8",
                                 capture_output=True, check=True).stdout
    cases = corpus(denied, manifest["examples"])
    # One original case per line keeps the shared generated fixture easy to compare.
    case_rows = ",\n".join("    " + json.dumps(row) for row in cases["cases"])
    fixture = '{\n  "schema": 1,\n  "cases": [\n' + case_rows + '\n  ]\n}\n'
    return {
        root / "crates/bridge/src/gateway_egress.rs": "\n".join(rust),
        root / "core/internal/bridgecontract/egress.go": formatted_go,
        root / "core/internal/bridgecontract/testdata/gateway-egress.json": fixture,
    }
