#!/usr/bin/env python3
"""Generate the Rust and Go local bridge contract from one manifest."""

import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
STRUCT_TYPES = {"string": ("String", "string"), "u64": ("u64", "uint64"), "u32": ("u32", "uint32"), "strings": ("Vec<String>", "[]string")}


def constant_value(row, root, resolved):
    """Resolve a literal, a JSON source field, or a previously declared constant."""
    if sum(key in row for key in ("source", "from_constant", "value")) != 1:
        raise ValueError("bridge constants must have exactly one value source")
    if "source" in row:
        source = row["source"]
        return json.loads((root / source["path"]).read_text(encoding="utf-8"))[source["field"]]
    if "from_constant" in row:
        return str(resolved[row["from_constant"]])
    return row["value"]


def string_list_values(row, resolved):
    """Return a literal list or the values selected from generated constants."""
    values = row.get("values")
    if values is None:
        values = [value for name, value in resolved.items() if name.startswith(row["prefix"])]
    if not values or any(not isinstance(value, str) or not value
                         or not value.isascii() for value in values):
        raise ValueError("bridge string lists must contain nonempty ASCII")
    return values


def declarations(manifest, root=ROOT):
    """Render unique, bounded constants, wire enums and structs for both bridge implementations."""
    if manifest["schema"] != 1:
        raise ValueError("unsupported bridge contract schema")
    constants = list(manifest["constants"])
    for enum in manifest.get("enums", []):
        for key in ("rust_name", "value"):
            values = [variant[key] for variant in enum["variants"]]
            if len(values) != len(set(values)):
                raise ValueError(f'duplicate enum {key} in {enum["rust_name"]}')
        constants.extend({"rust_name": "", "go_name": variant["go_name"],
                          "value": variant["value"], "rust_type": "str", "enum_value": True,
                          "doc": f'{enum["doc"]} {variant["rust_name"]}.'}
                         for variant in enum["variants"])
    for key in ("rust_name", "go_name"):
        names = [row[key] for row in constants if row[key]]
        names += [row[key] for row in manifest.get("string_lists", [])]
        if key == "rust_name":
            names += [row[key] for row in manifest.get("enums", [])]
        names += [row[key] for row in manifest.get("structs", [])]
        if len(names) != len(set(names)):
            raise ValueError(f"duplicate {key} in bridge contract")
    rust = ["// Generated by tools/bridgegen/generate.py; edit data/contract.json.",
            "", "use serde::{Deserialize, Serialize};"]
    go = ["// Code generated by tools/bridgegen/generate.py; DO NOT EDIT.",
          "// Package bridgecontract owns the local Rust/Go transport contract.",
          "package bridgecontract", "", "const ("]
    resolved = {}
    for row in constants:
        value = constant_value(row, root, resolved)
        if row["rust_name"]:
            resolved[row["rust_name"]] = value
        rust_type = row["rust_type"]
        if rust_type == "str":
            if (not isinstance(value, str) or not value.isascii()
                    or (not value and not row.get("enum_value", False))):
                raise ValueError("bridge strings must be ASCII and named constants must be nonempty")
            value = json.dumps(value)
            rust_type = "&str"
        else:
            bounds = {"u8": (1, 255), "u16": (1, 65535), "u32": (1, 2**32 - 1),
                      "usize": (1, 2**32 - 1), "i32": (-2**31, 2**31 - 1),
                      "i64": (-2**63, 2**63 - 1)}
            low, high = bounds[rust_type]
            if type(value) is not int or not low <= value <= high:
                raise ValueError("bridge contract values must fit their wire types")
        go += [f'    // {row["go_name"]}: {row["doc"]}', f'    {row["go_name"]} = {value}']
        if row["rust_name"]:
            visibility = "pub(crate)" if row["rust_name"] in ("CONTROL_MAX_FRAME_LEN", "MAX_PING_TARGETS") else "pub"
            rust += ["", f'/// {row["doc"]}',
                     f'{visibility} const {row["rust_name"]}: {rust_type} = {value};']
    for row in manifest.get("string_lists", []):
        entries = string_list_values(row, resolved)
        values = ", ".join(json.dumps(value) for value in entries)
        declaration = f'pub const {row["rust_name"]}: [&str; {len(entries)}] = '
        rust += ["", f'/// {row["doc"]}']
        if len(values) <= 60 and len(declaration + values) + 3 <= 100:
            rust += [declaration + f'[{values}];']
        else:
            rust += [declaration + '[']
            rust += [f'    {json.dumps(value)},' for value in entries]
            rust += ['];']
    for enum in manifest.get("enums", []):
        rust += ["", f'/// {enum["doc"]}', f'#[derive({", ".join(enum["derive"])})]']
        if enum.get("tag"):
            rust += [f'#[serde(tag = "{enum["tag"]}", content = "{enum["content"]}", deny_unknown_fields)]']
        rust += [f'pub enum {enum["rust_name"]} {{']
        for variant in enum["variants"]:
            if variant.get("doc"):
                rust += [f'    /// {variant["doc"]}']
            if variant.get("default"):
                rust += ["    #[default]"]
            rust += [f'    #[serde(rename = {json.dumps(variant["value"])})]']
            if variant.get("other"):
                rust += ["    #[serde(other)]"]
            payload = "(String)" if enum.get("content") else ""
            rust += [f'    {variant["rust_name"]}{payload},']
        rust += ["}"]
    def field_types(field):
        """Resolve primitive fields or lists of declared contract records in both languages."""
        kind = field["type"]
        if kind in STRUCT_TYPES:
            return STRUCT_TYPES[kind]
        if kind.startswith("list:"):
            name = kind.removeprefix("list:")
            record = next((row for row in manifest.get("structs", []) if row["rust_name"] == name), None)
            if record is not None:
                return f"Vec<{name}>", f"[]{record['go_name']}"
        raise ValueError(f"unsupported field type: {kind}")

    for struct in manifest.get("structs", []):
        rust += ["", f'/// {struct["doc"]}', f'#[derive({", ".join(struct["derive"])})]',
                 f'pub struct {struct["rust_name"]} {{']
        for field in struct["fields"]:
            rust += [f'    /// {field["doc"]}']
            if field.get("default"):
                rust += ["    #[serde(default)]"]
            rust_type = field_types(field)[0]
            rust += [f'    pub {field["name"]}: {rust_type},']
        rust += ["}"]
    go.append(")")
    for struct in manifest.get("structs", []):
        go += ["", f'// {struct["go_name"]}: {struct["doc"]}', f'type {struct["go_name"]} struct {{']
        for field in struct["fields"]:
            go += [f'    // {field["go_name"]}: {field["doc"]}',
                   f'    {field["go_name"]} {field_types(field)[1]} `json:"{field["name"]}"`']
        go.append("}")
    for row in manifest.get("string_lists", []):
        values = ", ".join(json.dumps(value) for value in string_list_values(row, resolved))
        go += ["", f'// {row["go_name"]}: {row["doc"]}',
               f'var {row["go_name"]} = [...]string{{{values}}}']
    formatted = subprocess.run(["gofmt"], input="\n".join(go) + "\n", encoding="utf-8",
                               capture_output=True, check=True).stdout
    return {ROOT / "crates/bridge/src/contract.rs": "\n".join(rust) + "\n",
            ROOT / "core/internal/bridgecontract/contract.go": formatted}


def main():
    """Regenerate constants or reject stale checked-in declarations."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest = json.loads((ROOT / "crates/bridge/data/contract.json").read_text(encoding="utf-8"))
    for path, content in declarations(manifest).items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                parser.exit(1, f"stale bridge contract: {path.relative_to(ROOT)}\n")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
