//! Validates fixed presentation identities and compiles the shared naming rules.

use super::{Result, check};
use serde::Deserialize;
use std::{
    collections::{BTreeMap, BTreeSet},
    path::Path,
};

pub const GENERATED_PATH: &str = "crates/assets/src/facts/presentation_generated.rs";

#[derive(Default, Deserialize)]
#[serde(deny_unknown_fields)]
pub(super) struct Rules {
    status: String,
    item_icons: BTreeMap<String, String>,
    dimensions: BTreeMap<i32, [String; 2]>,
    ambient_blocks: BTreeMap<String, Vec<String>>,
    sign_suffixes: Vec<String>,
    sign_wood_aliases: BTreeMap<String, String>,
    sign_wood_first: Vec<String>,
}

/// Checks identities against their pinned domains before emitting shared presentation facts.
pub fn write(out: &Path) -> Result<()> {
    let policy: super::Policy = serde_json::from_slice(super::POLICY)?;
    let rules = policy.presentation;
    check(
        rules.status == "provisional",
        "presentation rules need explicit status",
    )?;
    let items = assets::item::retail::identifiers();
    let biomes: BTreeSet<_> = include_str!("../../../protocol/data/retail_biomes_1_26_50.txt")
        .lines()
        .collect();
    let blocks = assets::read_registry_for_protocol(
        assets::pinned_block_registry_bytes(),
        assets::active_content_registry_protocol(),
    )?;
    let block_names: BTreeSet<_> = blocks.iter().map(|block| block.name.as_ref()).collect();
    let quote = |text: &str| serde_json::to_string(text);
    let mut text = String::from("// @generated by registryc; do not edit.\n\n");
    text.push_str("macro_rules! icons { ($($variant:ident => $name:literal,)+) => {\n/// Fixed item artwork requested by product UI.\n#[derive(Clone, Copy, Debug)]\npub enum UiItemIcon { $($variant,)+ }\nimpl UiItemIcon {\n/// Every admitted artwork role.\npub const ALL: &'static [Self] = &[$(Self::$variant),+];\n/// The pinned item identity used by this artwork role.\npub const fn identifier(self) -> &'static str { match self { $(Self::$variant => $name,)+ } }\n}\n}; }\nicons! {\n");
    for (variant, name) in &rules.item_icons {
        check(
            items.contains(name.as_str()),
            format!("unknown UI item {name}"),
        )?;
        check(
            !variant.is_empty() && variant.chars().all(|ch| ch.is_ascii_alphanumeric()),
            "invalid UI icon role",
        )?;
        text.push_str(&format!("{variant} => {},\n", quote(name)?));
    }
    text.push_str("}\n\n/// The fallback biome for a supported protocol dimension.\npub const fn dimension_fallback_biome(dimension: i32) -> Option<&'static str> { match dimension {\n");
    for (id, [_, biome]) in &rules.dimensions {
        check(
            biomes.contains(biome.as_str()),
            format!("unknown fallback biome {biome}"),
        )?;
        text.push_str(&format!("{id} => Some({}),\n", quote(biome)?));
    }
    text.push_str("_ => None, } }\n\n/// Admits a canonical dimension name before custom numeric definitions.\npub fn dimension_id(name: &str) -> Option<i32> { match name {\n");
    for (id, [name, _]) in &rules.dimensions {
        text.push_str(&format!("{} => Some({id}),\n", quote(name)?));
    }
    text.push_str("_ => None, } }\n\n/// Resolves an ambient callback once during block admission.\npub(super) fn ambient_block(name: &str) -> super::presentation::AmbientBlock { match name {\n");
    let mut seen = BTreeSet::new();
    for (kind, names) in &rules.ambient_blocks {
        check(
            matches!(kind.as_str(), "Fire" | "Portal"),
            "unknown ambient callback",
        )?;
        check(!names.is_empty(), "empty ambient selector")?;
        for name in names {
            check(
                block_names.contains(name.as_str()) && seen.insert(name),
                "unknown or duplicate ambient block",
            )?;
            text.push_str(&format!(
                "{} => super::presentation::AmbientBlock::{kind},\n",
                quote(name)?
            ));
        }
    }
    text.push_str("_ => super::presentation::AmbientBlock::Other, } }\n");
    for (name, values) in [
        ("SIGN_SUFFIXES", &rules.sign_suffixes),
        ("SIGN_WOOD_FIRST", &rules.sign_wood_first),
    ] {
        check(!values.is_empty(), "empty sign naming rule")?;
        text.push_str(&format!(
            "pub(super) const {name}: &[&str] = &{};\n",
            serde_json::to_string(values)?
        ));
    }
    text.push_str("pub(super) const SIGN_WOOD_ALIASES: &[(&str, &str)] = &[\n");
    for (wood, alias) in &rules.sign_wood_aliases {
        text.push_str(&format!("({}, {}),\n", quote(wood)?, quote(alias)?));
    }
    text.push_str("];\n");
    super::manifest::write(out, text.as_bytes())?;
    let status = std::process::Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(out)
        .status()?;
    check(status.success(), "presentation facts formatting")
}
