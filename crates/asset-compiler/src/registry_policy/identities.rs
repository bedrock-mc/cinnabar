//! Compile exact native asset requests from the version-bound identity rules.

use super::{Result, check};
use std::{collections::BTreeSet, path::Path};

pub const GENERATED_PATH: &str = "crates/assets/src/facts/identities_generated.rs";

/// Validates each native request against its pinned registry before emitting typed identities.
pub fn write(out: &Path) -> Result<()> {
    let policy: super::Policy = serde_json::from_slice(super::POLICY)?;
    let mut text = String::from("// @generated by registryc; do not edit.\n\n");
    for (domain, members) in policy.runtime_identifiers {
        let names: BTreeSet<String> = match domain.as_str() {
            "VanillaItem" => assets::facts::ItemFacts::builtin()?
                .payload()
                .records
                .iter()
                .map(|r| r.identifier.to_string())
                .collect(),
            "VanillaBlock" => assets::read_registry_for_protocol(
                assets::pinned_block_registry_bytes(),
                assets::active_content_registry_protocol(),
            )?
            .into_iter()
            .map(|r| r.name.to_string())
            .collect(),
            "VanillaEntity" => assets::facts::entity::EntityFacts::pinned()
                .records
                .iter()
                .map(|r| r.identifier.to_string())
                .collect(),
            _ => return Err("unknown native identity domain".into()),
        };
        check(!members.is_empty(), "empty native identity domain")?;
        text.push_str(&format!("/// Exact {domain} requests validated against the pinned registry.\n#[derive(Clone, Copy, Debug, Eq, PartialEq)]\npub enum {domain} {{\n"));
        for (variant, name) in &members {
            check(
                names.contains(name),
                format!("unknown native identity {name}"),
            )?;
            check(
                variant.chars().all(|c| c.is_ascii_alphanumeric())
                    && variant.starts_with(char::is_uppercase),
                "invalid identity variant",
            )?;
            text.push_str(&format!("    {variant},\n"));
        }
        text.push_str(&format!("}}\nimpl {domain} {{\n/// Resolves this native asset request without a runtime name table.\npub const fn identifier(self) -> &'static str {{ match self {{\n"));
        for (variant, name) in &members {
            text.push_str(&format!(
                "Self::{variant} => {},\n",
                serde_json::to_string(name)?
            ));
        }
        text.push_str("}}\n}\n");
    }
    super::manifest::write(out, text.as_bytes())?;
    let status = std::process::Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(out)
        .status()?;
    check(status.success(), "identity table formatting")
}

/// Native singleton requests remain deterministic and reject stale identifiers.
#[test]
fn compiled_native_requests_regenerate_byte_for_byte() {
    let scratch = tempfile::tempdir().unwrap();
    let out = scratch.path().join("identities.rs");
    write(&out).unwrap();
    assert_eq!(
        std::fs::read(out).unwrap(),
        include_bytes!("../../../assets/src/facts/identities_generated.rs")
    );
}
