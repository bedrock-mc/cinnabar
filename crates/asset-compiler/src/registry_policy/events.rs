//! Compile native event routes into the shared numeric facts owner.

use super::{Result, check};
use serde::Deserialize;
use std::{
    collections::{BTreeMap, BTreeSet},
    path::Path,
};

pub const GENERATED_PATH: &str = "crates/assets/src/facts/events_generated.rs";

#[derive(Default, Deserialize)]
#[serde(deny_unknown_fields)]
pub(super) struct Rules {
    status: String,
    legacy_particles: BTreeMap<i32, String>,
    level_particles: BTreeMap<String, String>,
    level_sounds: Vec<(String, String, String)>,
    note_instruments: Vec<String>,
}

/// Validates and writes deterministic event tables without compiling pack artwork.
pub fn write(out: &Path) -> Result<()> {
    let policy: super::Policy = serde_json::from_slice(super::POLICY)?;
    let rules = policy.visual_events;
    check(
        rules.status == "provisional",
        "event rules require explicit provisional status",
    )?;
    let particles: BTreeSet<_> =
        include_str!("../../../assets/data/vanilla-pack-vocabulary-1.26.50.tsv")
            .lines()
            .filter_map(|row| row.strip_prefix("particle\t"))
            .collect();
    for effect in rules
        .legacy_particles
        .values()
        .chain(rules.level_particles.values())
    {
        check(
            particles.contains(format!("minecraft:{effect}").as_str()),
            "unknown particle route",
        )?;
    }
    check(
        rules.legacy_particles.keys().all(|id| *id > 0),
        "invalid legacy particle id",
    )?;
    let event_id = |name: &str| -> Result<i32> {
        protocol_ids::LevelEvent::from_name(name)
            .map(|event| event.wire_value())
            .ok_or_else(|| format!("unknown presentation event {name}").into())
    };
    let level_particles = rules
        .level_particles
        .iter()
        .map(|(name, effect)| Ok((event_id(name)?, effect.clone())))
        .collect::<Result<BTreeMap<i32, String>>>()?;
    let mut level_sounds = rules
        .level_sounds
        .iter()
        .map(|(name, event, sound)| Ok((event_id(name)?, event.clone(), sound.clone())))
        .collect::<Result<Vec<_>>>()?;
    level_sounds.sort_by_key(|row| row.0);
    check(
        level_sounds.windows(2).all(|pair| pair[0].0 < pair[1].0),
        "duplicate sound event",
    )?;
    check(!rules.note_instruments.is_empty(), "empty note inventory")?;
    let mut text = String::from("// @generated by registryc; do not edit.\n\n");
    text.push_str("macro_rules! particle_effects { ($($variant:ident => $name:literal,)+) => {\n#[derive(Clone, Copy, Debug, Eq, PartialEq)]\npub enum ParticleEffect { $($variant,)+ }\nimpl ParticleEffect {\n/// Every effect in the pinned particle vocabulary.\npub const ALL: &'static [Self] = &[$(Self::$variant),+];\n/// The pack identifier used by native particle triggers.\npub const fn name(self) -> &'static str { match self { $(Self::$variant => $name,)+ } }\n/// Admits a native effect name once while loading an artwork library.\npub fn from_name(name: &str) -> Option<Self> { match name.strip_prefix(\"minecraft:\").unwrap_or(name) { $($name => Some(Self::$variant),)+ _ => None } }\n}\n}; }\nparticle_effects! {\n");
    let mut variants = BTreeSet::new();
    for name in &particles {
        let bare = name
            .strip_prefix("minecraft:")
            .ok_or("non-builtin particle vocabulary entry")?;
        let variant = effect_variant(bare);
        check(
            variants.insert(variant.clone()),
            "colliding particle variants",
        )?;
        text.push_str(&format!(
            "    {variant} => {},\n",
            serde_json::to_string(bare)?
        ));
    }
    text.push_str("}\n\n");
    emit(
        &mut text,
        "LEGACY_PARTICLES",
        "(i32, ParticleEffect)",
        rules.legacy_particles,
    )?;
    emit(
        &mut text,
        "LEVEL_PARTICLES",
        "(i32, ParticleEffect)",
        level_particles,
    )?;
    emit(&mut text, "LEVEL_SOUNDS", "(i32, &str, &str)", level_sounds)?;
    emit(
        &mut text,
        "NOTE_INSTRUMENTS",
        "&str",
        rules.note_instruments,
    )?;
    super::manifest::write(out, text.as_bytes())?;
    let status = std::process::Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(out)
        .status()?;
    check(status.success(), "event table formatting")
}

/// Emits JSON-compatible scalar tuples as bounded Rust constant arrays.
fn emit<T: serde::Serialize>(
    text: &mut String,
    name: &str,
    ty: &str,
    rows: impl IntoIterator<Item = T>,
) -> Result<()> {
    text.push_str(&format!("pub(super) const {name}: &[{ty}] = &[\n"));
    for row in rows {
        let json = serde_json::to_value(row)?;
        let value = if ty == "(i32, ParticleEffect)" {
            let values = json.as_array().ok_or("invalid particle row")?;
            format!(
                "({}, ParticleEffect::{})",
                values[0],
                effect_variant(values[1].as_str().ok_or("invalid particle name")?)
            )
        } else {
            match json {
                serde_json::Value::Array(values) => format!(
                    "({})",
                    values
                        .iter()
                        .map(serde_json::to_string)
                        .collect::<std::result::Result<Vec<_>, _>>()?
                        .join(", ")
                ),
                value => serde_json::to_string(&value)?,
            }
        };
        text.push_str(&format!("    {value},\n"));
    }
    text.push_str("];\n\n");
    Ok(())
}

/// Converts a validated particle identifier to a unique Rust variant.
fn effect_variant(name: &str) -> String {
    name.split('_')
        .map(|part| {
            let mut chars = part.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_uppercase().collect::<String>() + chars.as_str()
            })
        })
        .collect()
}
