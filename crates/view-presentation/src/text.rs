//! Text limits shared by retained presentation surfaces.

pub const MAX_PRESENTED_TEXT_BYTES: usize = 512;

pub fn bounded_visible_text(value: &str) -> &str {
    if value.len() <= MAX_PRESENTED_TEXT_BYTES {
        return value;
    }
    let mut end = MAX_PRESENTED_TEXT_BYTES;
    while !value.is_char_boundary(end) {
        end -= 1;
    }
    &value[..end]
}
