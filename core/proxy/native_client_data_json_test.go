package proxy

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"path/filepath"
	"runtime"
	"strconv"
	"testing"
)

// nativeClientDataJSON derives the one nesting limit from this test's actual standard library.
func nativeClientDataJSON(t *testing.T) []byte {
	t.Helper()
	if runtime.GOROOT() == "" {
		t.Fatal("the current Go standard-library source is unavailable")
	}
	path := filepath.Join(runtime.GOROOT(), "src", "encoding", "json", "scanner.go")
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		t.Fatal(err)
	}
	var depth uint64
	for _, declaration := range file.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok || general.Tok != token.CONST {
			continue
		}
		for _, specification := range general.Specs {
			value, ok := specification.(*ast.ValueSpec)
			if !ok || len(value.Names) != 1 || value.Names[0].Name != "maxNestingDepth" {
				continue
			}
			if depth != 0 || len(value.Values) != 1 || value.Type != nil {
				t.Fatal("unexpected duplicate or typed Go JSON nesting limit")
			}
			literal, ok := value.Values[0].(*ast.BasicLit)
			if !ok || literal.Kind != token.INT {
				t.Fatal("unexpected Go JSON nesting-limit expression")
			}
			depth, err = strconv.ParseUint(literal.Value, 0, 32)
			if err != nil || depth == 0 {
				t.Fatal("invalid Go JSON nesting limit")
			}
		}
	}
	if depth == 0 {
		t.Fatal("missing identified Go JSON nesting limit")
	}
	t.Logf("actual Go JSON maximum nesting depth: %d", depth)
	return fmt.Appendf(nil,
		"// Generated by TestNativeClientDataSemanticData from Go encoding/json/scanner.go.\n"+
			"// Go JSON data are BSD licensed; see THIRD_PARTY_NOTICES.md.\n\n"+
			"pub(super) const MAX_NESTING_DEPTH: usize = %d;\n", depth,
	)
}
