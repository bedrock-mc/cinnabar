const nativeClientDataSchemaPath = "../../crates/protocol/src/login/client_data/raw/schema_generated.rs"

var updateNativeClientDataSchema = flag.Bool(
	"update-native-client-data-schema", false, "write the reflected native client-data Rust schema",
)

type nativeSchemaRecord struct {
	name   string
	typeOf reflect.Type
}

type nativeSchemaField struct {
	name string
	kind string
	tag  string
}

type nativeSchemaSource struct {
	importModule string
	module       string
	version      string
	sum          string
}

// TestNativeClientDataSchema checks the Rust descriptor against the actual compiled Go dependency.
// Writing requires the explicit update flag; ordinary tests only compare the generated bytes.
func TestNativeClientDataSchema(t *testing.T) {
	records := []nativeSchemaRecord{
		{name: "Client", typeOf: reflect.TypeFor[login.ClientData]()},
		{name: "Animation", typeOf: reflect.TypeFor[login.SkinAnimation]()},
		{name: "PersonaPiece", typeOf: reflect.TypeFor[login.PersonaPiece]()},
		{name: "Tint", typeOf: reflect.TypeFor[login.PersonaPieceTintColour]()},
	}
	source := nativeClientDataSchemaSource(t, records[0].typeOf.PkgPath())
	generated := nativeClientDataSchema(t, records, source)
	if *updateNativeClientDataSchema {
		if err := os.WriteFile(nativeClientDataSchemaPath, generated, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf(
			"wrote %s from %s %s %s",
			nativeClientDataSchemaPath,
			source.module,
			source.version,
			source.sum,
		)
		return
	}
	existing, err := os.ReadFile(nativeClientDataSchemaPath)
	if err != nil {
		t.Fatalf("read generated schema: %v; run this test with -update-native-client-data-schema", err)
	}
	if !bytes.Equal(existing, generated) {
		t.Fatal("native client-data schema drifted; regenerate and review the changed dependency/type graph")
	}
}

// nativeClientDataSchema renders only the four concrete record owners and their finite field kinds.
func nativeClientDataSchema(t *testing.T, records []nativeSchemaRecord, source nativeSchemaSource) []byte {
	t.Helper()
	var out strings.Builder
	out.WriteString("// Generated by TestNativeClientDataSchema from the active Go ClientData type.\n")
	out.WriteString("// Regenerate through the owning Go test; do not edit.\n")
	out.WriteString("// Gophertunnel metadata is MIT licensed; see THIRD_PARTY_NOTICES.md.\n\n")
	for _, row := range []struct{ name, value string }{
		{name: "SOURCE_IMPORT_MODULE", value: source.importModule},
		{name: "SOURCE_MODULE", value: source.module},
		{name: "SOURCE_VERSION", value: source.version},
		{name: "SOURCE_SUM", value: source.sum},
	} {
		fmt.Fprintf(
			&out,
			"#[cfg(test)]\npub(super) const %s: &str = %s;\n\n",
			row.name,
			strconv.Quote(row.value),
		)
	}
	out.WriteString("#[derive(Clone, Copy, Debug, Eq, PartialEq)]\npub(super) enum Record {\n")
	for _, record := range records {
		fmt.Fprintf(&out, "    %s,\n", record.name)
	}
	out.WriteString("}\n\n#[derive(Clone, Copy, Debug, Eq, PartialEq)]\npub(super) enum Kind {\n")
	out.WriteString("    String,\n    Integer(u8),\n    Bool,\n    OptionalBool,\n    Float64,\n" +
		"    Slice(Record),\n    Strings(usize),\n}\n\n")
	out.WriteString("#[derive(Clone, Copy, Debug)]\npub(super) struct Field {\n")
	out.WriteString("    pub(super) name: &'static str,\n    pub(super) kind: Kind,\n}\n\n")
	out.WriteString("impl Record {\n    pub(super) fn fields(self) -> &'static [Field] {\n        match self {\n")
	for _, record := range records {
		fmt.Fprintf(
			&out,
			"            Self::%s => %s_FIELDS,\n",
			record.name,
			strings.ToUpper(record.name),
		)
	}
	out.WriteString("        }\n    }\n}\n")
	for _, record := range records {
		fields := nativeClientDataSchemaFields(t, record, records)
		t.Logf("%s: %d modeled fields", record.typeOf, len(fields))
		fmt.Fprintf(&out, "\nconst %s_FIELDS: &[Field] = &[\n", strings.ToUpper(record.name))
		for _, field := range fields {
			if field.tag != "" {
				fmt.Fprintf(&out, "    // json:%s\n", strconv.Quote(field.tag))
			}
			fmt.Fprintf(
				&out,
				"    Field {\n        name: %s,\n        kind: %s,\n    },\n",
				strconv.Quote(field.name),
				field.kind,
			)
		}
		out.WriteString("];\n")
	}
	return []byte(out.String())
}

// nativeClientDataSchemaFields honors JSON names and rejects decoding shapes outside this owner.
func nativeClientDataSchemaFields(t *testing.T, record nativeSchemaRecord, records []nativeSchemaRecord) []nativeSchemaField {
	t.Helper()
	if record.typeOf.Kind() != reflect.Struct {
		t.Fatalf("unsupported record %s", record.typeOf)
	}
	nativeClientDataSchemaDecoder(t, record.typeOf, record.typeOf == records[0].typeOf)
	fields := []nativeSchemaField{}
	folded := map[string]bool{}
	for index := range record.typeOf.NumField() {
		field := record.typeOf.Field(index)
		if field.Anonymous {
			t.Fatalf("unsupported embedded field %s.%s", record.typeOf, field.Name)
		}
		if !field.IsExported() || field.Tag.Get("json") == "-" {
			continue
		}
		name := field.Name
		tag := field.Tag.Get("json")
		parts := strings.Split(tag, ",")
		if parts[0] != "" {
			name = parts[0]
		}
		for _, option := range parts[1:] {
			if option != "omitempty" {
				t.Fatalf("unsupported JSON option %q on %s.%s", option, record.typeOf, field.Name)
			}
		}
		for _, character := range name {
			if character < ' ' || character > '~' || character == '"' || character == '\\' {
				t.Fatalf("unsupported JSON name %q", name)
			}
		}
		key := strings.ToUpper(name)
		if folded[key] {
			t.Fatalf("unsupported folded JSON-name collision %q in %s", name, record.typeOf)
		}
		folded[key] = true
		fields = append(fields, nativeSchemaField{
			name: name, kind: nativeClientDataSchemaKind(t, field.Type, records), tag: tag,
		})
	}
	return fields
}

// nativeClientDataSchemaKind emits a closed descriptor, never an arbitrary recursive schema.
func nativeClientDataSchemaKind(t *testing.T, value reflect.Type, records []nativeSchemaRecord) string {
	t.Helper()
	nativeClientDataSchemaDecoder(t, value, false)
	switch value.Kind() {
	case reflect.String:
		return "Kind::String"
	case reflect.Int, reflect.Int64:
		return fmt.Sprintf("Kind::Integer(%d)", value.Bits())
	case reflect.Bool:
		return "Kind::Bool"
	case reflect.Float64:
		return "Kind::Float64"
	case reflect.Pointer:
		if value.Elem() == reflect.TypeFor[bool]() {
			return "Kind::OptionalBool"
		}
	case reflect.Array:
		if value.Elem() == reflect.TypeFor[string]() {
			return fmt.Sprintf("Kind::Strings(%d)", value.Len())
		}
	case reflect.Slice:
		for _, record := range records[1:] {
			if value.Elem() == record.typeOf {
				return "Kind::Slice(Record::" + record.name + ")"
			}
		}
	}
	t.Fatalf("unsupported native client-data type %s", value)
	return ""
}

// nativeClientDataSchemaDecoder permits only the already identified root JSON wrapper.
func nativeClientDataSchemaDecoder(t *testing.T, value reflect.Type, root bool) {
	t.Helper()
	jsonDecoder := reflect.TypeFor[json.Unmarshaler]()
	textDecoder := reflect.TypeFor[encoding.TextUnmarshaler]()
	hasJSON := value.Implements(jsonDecoder) || reflect.PointerTo(value).Implements(jsonDecoder)
	hasText := value.Implements(textDecoder) || reflect.PointerTo(value).Implements(textDecoder)
	if hasText || hasJSON != root {
		t.Fatalf("unsupported decoding wrapper on %s", value)
	}
}

// nativeClientDataSchemaSource uses compiled dependency metadata when available and the same Go tool otherwise.
func nativeClientDataSchemaSource(t *testing.T, packagePath string) nativeSchemaSource {
	t.Helper()
	importModule := nativeClientDataSchemaImportModule(t, packagePath)
	info, ok := debug.ReadBuildInfo()
	var selected *debug.Module
	if ok {
		for _, dependency := range info.Deps {
			if strings.HasPrefix(packagePath, dependency.Path+"/") {
				if selected == nil || len(dependency.Path) > len(selected.Path) {
					selected = dependency
				}
			}
		}
	}
	provider := "runtime/debug.ReadBuildInfo dependency"
	if selected == nil {
		provider = "GOROOT/bin/go list -mod=readonly -m -json metadata"
		listed := nativeClientDataModuleMetadata(t, importModule)
		selected = &listed.Module
	}
	if selected.Path != importModule || selected.Replace == nil {
		t.Fatal("native client-data source must have an identified compiled module replacement")
	}
	replacement := selected.Replace
	missingIdentity := replacement.Path == "" || replacement.Version == ""
	missingChecksum := replacement.Sum == ""
	if missingIdentity || missingChecksum || replacement.Replace != nil {
		t.Fatal("native client-data replacement needs a portable version and module checksum")
	}
	source := nativeSchemaSource{
		importModule: selected.Path, module: replacement.Path,
		version: replacement.Version, sum: replacement.Sum,
	}
	nativeClientDataSchemaPin(t, source)
	t.Logf("native client-data provenance: %s", provider)
	return source
}

// nativeClientDataSchemaImportModule selects the active replacement containing the reflected package.
func nativeClientDataSchemaImportModule(t *testing.T, packagePath string) string {
	t.Helper()
	selected := ""
	for _, pin := range nativeClientDataSchemaPins(t) {
		if !strings.HasPrefix(packagePath, pin.importModule+"/") {
			continue
		}
		if len(pin.importModule) > len(selected) {
			selected = pin.importModule
		}
	}
	if selected == "" {
		t.Fatal("the reflected native client-data package has no identified core replacement")
	}
	return selected
}

// nativeClientDataSchemaPins reads versioned replacements in inline or block form only.
func nativeClientDataSchemaPins(t *testing.T) []nativeSchemaSource {
	t.Helper()
	module, err := os.ReadFile("../go.mod")
	if err != nil {
		t.Fatal(err)
	}
	var pins []nativeSchemaSource
	block := false
	for index, line := range strings.Split(string(module), "\n") {
		line, _, _ = strings.Cut(line, "//")
		fields := strings.Fields(line)
		if len(fields) == 0 {
			continue
		}
		if block {
			if len(fields) == 1 && fields[0] == ")" {
				block = false
				continue
			}
		} else {
			if fields[0] != "replace" {
				continue
			}
			fields = fields[1:]
			if len(fields) == 1 && fields[0] == "(" {
				block = true
				continue
			}
		}
		if len(fields) != 4 || fields[1] != "=>" || strings.ContainsAny(strings.Join(fields, ""), "\"`()") {
			t.Fatalf("unsupported versioned module replacement on core/go.mod line %d", index+1)
		}
		pins = append(pins, nativeSchemaSource{
			importModule: fields[0], module: fields[2], version: fields[3],
		})
	}
	if block {
		t.Fatal("unterminated replacement block in core/go.mod")
	}
	return pins
}

// nativeListedModule retains the selected source directory without making it portable artifact metadata.
type nativeListedModule struct {
	debug.Module
	Dir string
}

// nativeClientDataModuleMetadata reads metadata under this test's Go toolchain without changing pins.
func nativeClientDataModuleMetadata(t *testing.T, importModule string) *nativeListedModule {
	t.Helper()
	if runtime.GOROOT() == "" {
		t.Fatal("the current Go toolchain root is unavailable")
	}
	tool := filepath.Join(runtime.GOROOT(), "bin", "go")
	if runtime.GOOS == "windows" {
		tool += ".exe"
	}
	command := exec.CommandContext(
		t.Context(),
		tool,
		"list",
		"-mod=readonly",
		"-m",
		"-json",
		importModule,
	)
	data, err := command.Output()
	if err != nil {
		t.Fatalf("read native client-data module metadata: %v", err)
	}
	var module nativeListedModule
	if err := json.Unmarshal(data, &module); err != nil {
		t.Fatalf("decode native client-data module metadata: %v", err)
	}
	return &module
}

// nativeClientDataSchemaPin rejects a build from a different replacement or an unrecognized pin form.
func nativeClientDataSchemaPin(t *testing.T, source nativeSchemaSource) {
	t.Helper()
	matches := 0
	for _, pin := range nativeClientDataSchemaPins(t) {
		if pin.importModule != source.importModule {
			continue
		}
		if pin.module != source.module || pin.version != source.version {
			t.Fatal("compiled native client-data replacement differs from the core go.mod pin")
		}
		matches++
	}
	if matches != 1 {
		t.Fatal("compiled native client-data replacement does not match the unique core go.mod pin")
	}
	sums, err := os.ReadFile("../go.sum")
	if err != nil {
		t.Fatal(err)
	}
	wanted := strings.Join([]string{source.module, source.version, source.sum}, " ")
	matches = 0
	for _, line := range strings.Split(string(sums), "\n") {
		if strings.Join(strings.Fields(line), " ") == wanted {
			matches++
		}
	}
	if matches != 1 {
		t.Fatal("compiled native client-data checksum does not match core go.sum")
	}
}
