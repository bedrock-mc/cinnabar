var updateNativeClientDataSemantics = flag.Bool(
	"update-native-client-data-semantics", false, "write the pinned Go metadata validation data",
)

// TestNativeClientDataSemanticData ties the finite Rust data to the actual selected Go owners.
// Ordinary tests only compare; an explicit developer update writes the generated artifacts.
func TestNativeClientDataSemanticData(t *testing.T) {
	client := nativeClientDataSchemaSource(t, reflect.TypeFor[login.ClientData]().PkgPath())
	locale := nativeClientDataLocaleSource(t)
	outputs := []struct {
		name string
		data []byte
	}{
		{"unicode_generated.rs", nativeClientDataUnicode(client, locale)},
		{"locale_generated.rs", nativeClientDataLocale(t, client, locale)},
		{"json_generated.rs", nativeClientDataJSON(t)},
	}
	for _, output := range outputs {
		path := filepath.Join("../../crates/protocol/src/login/client_data/raw/semantic", output.name)
		if *updateNativeClientDataSemantics {
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(path, output.data, 0o644); err != nil {
				t.Fatal(err)
			}
			t.Logf("wrote %s", path)
			continue
		}
		existing, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("read semantic data: %v; run with -update-native-client-data-semantics", err)
		}
		if !bytes.Equal(existing, output.data) {
			t.Fatalf("native metadata %s drifted; regenerate and review the selected Go owners", output.name)
		}
	}
}

// nativeClientDataLocaleSource verifies the selected direct module before reading its finite source maps.
func nativeClientDataLocaleSource(t *testing.T) *nativeListedModule {
	t.Helper()
	path, ok := strings.CutSuffix(reflect.TypeFor[language.Tag]().PkgPath(), "/language")
	if !ok {
		t.Fatal("unexpected language package owner")
	}
	module := nativeClientDataModuleMetadata(t, path)
	if module.Path != path || module.Replace != nil || module.Version == "" || module.Sum == "" || module.Dir == "" {
		t.Fatal("locale data requires the selected versioned direct module with source and checksum")
	}
	manifest, err := os.ReadFile("../go.mod")
	if err != nil {
		t.Fatal(err)
	}
	matches := 0
	for _, line := range strings.Split(string(manifest), "\n") {
		line, _, _ = strings.Cut(line, "//")
		fields := strings.Fields(line)
		if len(fields) == 3 && fields[0] == "require" {
			fields = fields[1:]
		}
		if len(fields) == 2 && fields[0] == path && fields[1] == module.Version {
			matches++
		}
	}
	if matches != 1 {
		t.Fatal("selected locale module differs from the unique core go.mod requirement")
	}
	sums, err := os.ReadFile("../go.sum")
	if err != nil {
		t.Fatal(err)
	}
	matches = 0
	wanted := strings.Join([]string{module.Path, module.Version, module.Sum}, " ")
	for _, line := range strings.Split(string(sums), "\n") {
		if strings.Join(strings.Fields(line), " ") == wanted {
			matches++
		}
	}
	if matches != 1 {
		t.Fatal("selected locale checksum differs from core go.sum")
	}
	return module
}

// nativeClientDataSemanticHeader records portable module identity, never the machine's source path.
func nativeClientDataSemanticHeader(client nativeSchemaSource, locale *nativeListedModule) *strings.Builder {
	var out strings.Builder
	out.WriteString("// Generated by TestNativeClientDataSemanticData; do not edit.\n")
	out.WriteString("// Go Unicode and x/text data are BSD licensed; see THIRD_PARTY_NOTICES.md.\n\n")
	for _, row := range []struct{ name, value string }{
		{"CLIENT_MODULE", client.module}, {"CLIENT_VERSION", client.version}, {"CLIENT_SUM", client.sum},
		{"LOCALE_MODULE", locale.Path}, {"LOCALE_VERSION", locale.Version}, {"LOCALE_SUM", locale.Sum},
		{"UNICODE_VERSION", unicode.Version},
	} {
		fmt.Fprintf(&out, "#[cfg(test)]\npub(super) const %s: &str = %s;\n\n", row.name, strconv.Quote(row.value))
	}
	return &out
}

// nativeClientDataUnicode emits the actual Go letter category including its original strides.
func nativeClientDataUnicode(client nativeSchemaSource, locale *nativeListedModule) []byte {
	out := nativeClientDataSemanticHeader(client, locale)
	out.WriteString("#[rustfmt::skip]\npub(super) const LETTER_RANGES: &[(u32, u32, u32)] = &[\n")
	for _, row := range unicode.L.R16 {
		fmt.Fprintf(out, "    (0x%x, 0x%x, %d),\n", row.Lo, row.Hi, row.Stride)
	}
	for _, row := range unicode.L.R32 {
		fmt.Fprintf(out, "    (0x%x, 0x%x, %d),\n", row.Lo, row.Hi, row.Stride)
	}
	out.WriteString("];\n")
	return []byte(out.String())
}

// nativeClientDataBits renders bounded accepted ASCII domains without an expanded string catalog.
func nativeClientDataBits(out *strings.Builder, name string, length int, accepts func(string) bool, alphabet string) {
	count := 1
	for range length {
		count *= len(alphabet)
	}
	bits := make([]byte, (count+7)/8)
	index := 0
	nativeClientDataEach(length, alphabet, func(word string) {
		if accepts(word) {
			bits[index/8] |= 1 << (index % 8)
		}
		index++
	})
	fmt.Fprintf(out, "#[rustfmt::skip]\npub(super) const %s: &[u8] = &[\n", name)
	for index, value := range bits {
		if index%16 == 0 {
			out.WriteString("    ")
		}
		fmt.Fprintf(out, "0x%02x,", value)
		if index%16 == 15 || index == len(bits)-1 {
			out.WriteByte('\n')
		} else {
			out.WriteByte(' ')
		}
	}
	out.WriteString("];\n\n")
}
